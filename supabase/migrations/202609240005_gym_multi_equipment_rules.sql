create or replace function public.gym_store_exercise_ids(target_store_id text)
returns table(exercise_id text)
language sql
stable
security invoker
set search_path = public
as $$
  with available_equipment as (
    select gse.equipment_id
    from public.gym_store_equipment gse
    where gse.store_id = target_store_id
      and gse.available = true
  ),
  direct_exercises as (
    select distinct eem.exercise_id
    from available_equipment a
    join public.equipment_exercise_mapping eem
      on eem.equipment_id = a.equipment_id
  ),
  satisfied_rules as (
    select r.exercise_id
    from public.exercise_equipment_rules r
    join public.exercise_equipment_rule_items ri
      on ri.rule_id = r.id
    left join available_equipment a
      on a.equipment_id = ri.equipment_id
    group by r.id, r.exercise_id
    having count(*) = count(a.equipment_id)
  )
  select d.exercise_id from direct_exercises d
  union
  select s.exercise_id from satisfied_rules s;
$$;

