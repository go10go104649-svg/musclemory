-- Multi-equipment exercise availability for gym store filtering.
begin;

create table if not exists public.exercise_equipment_rules (
  id text primary key,
  exercise_id text not null check(length(exercise_id) > 0),
  rationale text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.exercise_equipment_rule_items (
  rule_id text not null references public.exercise_equipment_rules(id) on delete cascade,
  equipment_id text not null references public.equipment(id) on delete cascade,
  primary key(rule_id, equipment_id)
);

create index if not exists exercise_equipment_rules_exercise_idx
  on public.exercise_equipment_rules(exercise_id);
create index if not exists exercise_equipment_rule_items_equipment_idx
  on public.exercise_equipment_rule_items(equipment_id);

alter table public.exercise_equipment_rules enable row level security;
alter table public.exercise_equipment_rule_items enable row level security;

revoke all on public.exercise_equipment_rules, public.exercise_equipment_rule_items
  from anon, authenticated;
grant select on public.exercise_equipment_rules, public.exercise_equipment_rule_items
  to anon, authenticated;

drop policy if exists exercise_equipment_rules_read on public.exercise_equipment_rules;
create policy exercise_equipment_rules_read on public.exercise_equipment_rules
  for select to anon, authenticated using (true);

drop policy if exists exercise_equipment_rule_items_read on public.exercise_equipment_rule_items;
create policy exercise_equipment_rule_items_read on public.exercise_equipment_rule_items
  for select to anon, authenticated using (true);

